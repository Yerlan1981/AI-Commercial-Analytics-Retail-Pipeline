import pandas as pd
import numpy as np

# 1. Фиксируем случайность
np.random.seed(10)

# 2. Имитируем грязный отчет менеджера по продажам (sales_raw.csv)
# Специально добавляем пропуски (None), лишние пробелы в текстовые поля и кривой формат дат
df_sales_raw = pd.DataFrame({
    "transaction_id":[101, 102, 103, 104, 105, 106],
    "client_id":[1, 2, 99, 3, 1, 2], # 99 - несуществующий клиент (ошибка менеджера)
    "date": ["2026-10-01", "2026.10.01", "01-10-2026", "2026/10/02", "2026-10-02", None], # Каша в датах и пропуск
    "amount": [15000, 22000, None, 45000, 12000, 30000] # Пропуск в сумме
})

# 3. Имитируем справочник клиентов из CRM (customers_raw.csv)
# Специально добавляем невидимые пробелы в имена и города, чтобы усложнить задачу
df_customers_raw = pd.DataFrame({
    "client_id":[1, 2, 3, 4],
    "client_name": [" Султан ", "Айгерим", " Дмитрий", "Елена"], # Пробелы по краям
    "city": ["Алматы ", " Астана", "Шымкент", "Караганда"]
})

# 4. Сохраняем эти грязные файлы на диск, как будто они прилетели из базы данных
df_sales_raw.to_csv("sales_raw.csv", index=False)
df_customers_raw.to_csv("customers_raw.csv", index=False)

print("--- Шаг 1 выполнен успешно ---")
print("Сырые файлы 'sales_raw.csv' и 'customers_raw.csv' сгенерированы на диске!")

# --- ШАГ №2: ЗАГРУЗКА И ОЧИСТКА ТЕКСТОВЫХ ПОЛЕЙ ОТ ПРОБЕЛОВ ---

# 1. Робот считывает сырые файлы с диска
sales = pd.read_csv("sales_raw.csv")
customers = pd.read_csv("customers_raw.csv")

# 2. Чистим текстовые столбцы в справочнике клиентов от невидимых пробелов
customers["client_name"] = customers["client_name"].str.strip()
customers["city"] = customers["city"].str.strip()

print("\n--- Шаг 2: Справочник клиентов после очистки от пробелов ---")
print(customers)

# --- ШАГ №3: ИСПРАВЛЕНИЕ КАШИ В ФОРМАТАХ ДАТ ---

# Универсальный конвертер Pandas приводит любые разделители к эталону ГГГГ-ММ-ДД
# Параметр errors="coerce" автоматически превратит пропуски и критические ошибки в NaT (Not a Time)
sales["date"] = pd.to_datetime(sales["date"], errors="coerce")

print("\n--- Шаг 3: Таблица продаж после стандартизации дат ---")
print(sales)

# --- ШАГ №4: СПАСЕНИЕ ДАННЫХ (ЗАПОЛНЕНИЕ ПРОПУСКОВ) И СЛИЯНИЕ ---

# 1. Вместо удаления там где есть суммы, но нет дат заполняем пустые даты (NaT) первым числом октября
sales["date"] = sales["date"].fillna(pd.to_datetime("2026-10-01"))

# 2. А вот строки, где пропущена САМА СУММА (NaN), мы вынуждены удалить, 
# так как мы не можем угадать, сколько денег принес клиент.
sales_clean = sales.dropna(subset=["amount"])

# 3. Склеиваем спасенные продажи со справочником клиентов
df_final_report = pd.merge(sales_clean, customers, on="client_id", how="inner")

print("\n--- Шаг 4: Финальный бизнес-отчет со спасенными продажами ---")
print(df_final_report)

# --- ШАГ №5: АВТОМАТИЧЕСКИЙ ЭКСПОРТ ЧИСТОГО ОТЧЕТА НА ДИСК ---

# Сохраняем финальную таблицу в файл 'final_clean_report.csv'
# Параметр index=False нужен, чтобы в файл не лезли лишние технические цифры строк
df_final_report.to_csv("final_clean_report.csv", index=False)

print("\n--- Шаг 5 выполнен успешно! ---")
print("Идеальный отчет 'final_clean_report.csv' сохранен и готов для Power BI!")

# --- ФИНАЛЬНЫЙ АВТОМАТИЧЕСКИЙ ЭКСПОРТ В ПАПКУ ДЛЯ POWER BI ---

