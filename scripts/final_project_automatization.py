target_path = r"E:\sh0tny1\рабочий стол\Yerlan\инфо по курсу Python без видео\файлы csv для Power BI\final_clean_report.csv"

# Сохраняем очищенный шедевр прямо туда
df_final_report.to_csv(target_path, index=False)

print("\n--- Шаг 5: Идеальный файл отправлен в целевую папку для Power BI! ---")
