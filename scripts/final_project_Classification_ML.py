import pandas as pd
import numpy as np
from sklearn.linear_model import LogisticRegression

# 1. Фиксируем случайность
np.random.seed(42)

# 2. Имитируем базу кредитного отдела (4 исторических клиента)
# income_kZT - доход клиента в тысячах тенге (Фактор X1)
# credit_score - скоринговый балл от 1 до 10 (Фактор X2)
# approved_and_paid (y) - целевой класс: 1 - вернул, 0 - не вернул (дефолт)
df_bank_history = pd.DataFrame({
    "income_kZT":[400, 600, 300, 800],
    "credit_score":[5, 8, 3, 9],
    "approved_and_paid": [0, 1, 0, 1]
})

print("--- Шаг 1: Историческая база кредитного скоринга создана ---")
print(df_bank_history)

# --- ШАГ №2: МНОЖЕСТВЕННЫЕ ФАКТОРЫ (X) И ЦЕЛЕВОЙ КЛАСС (y) ---

# Выделяем матрицу признаков X (передаем сразу два столбца-причины в двойных скобках)
X = df_bank_history[["income_kZT", "credit_score"]]

# Выделяем вектор целевого класса y (бинарная метка: 1 или 0)
y = df_bank_history["approved_and_paid"]

print("\n--- Шаг 2: Данные успешно разделены на X и y ---")
print("Формат матрицы факторов X (строки, колонки):", X.shape)

# --- ШАГ №3: ИНИЦИАЛИЗАЦИЯ И ОБУЧЕНИЕ МОДЕЛИ КЛАССИФИКАЦИИ ИИ ---

# 1. Создаем пустой "мозг" модели Логистической Регрессии
model_classifier = LogisticRegression()

# 2. Запускаем обучение конвейера! ИИ ищет математическую границу разделения классов
model_classifier.fit(X, y)

print("\n--- Шаг 3: Модель ИИ (Классификатор) успешно обучена на кредитной истории! ---")

# --- ШАГ №4: КРЕДИТНЫЙ СКОРИНГ (ПРОГНОЗИРОВАНИЕ) ДЛЯ НОВЫХ КЛИЕНТОВ ---

# 1. Загружаем анкеты двух новых клиентов (у них есть доход и рейтинг, но нет меток)
# Клиент 1: Доход 500 тыс, рейтинг 7
# Клиент 2: Доход 250 тыс, рейтинг 2
X_new_customers = pd.DataFrame({
    "income_kZT":[500, 200],
    "credit_score": [7, 2]
})

# 2. Обученный ИИ прогоняет анкеты через свою математическую границу
predictions = model_classifier.predict(X_new_customers)

# 3. Объединяем анкеты и вердикты ИИ в один красивый коммерческий отчет
df_scoring_report = X_new_customers.copy()
df_scoring_report["AI_Decision"] = predictions

print("\n--- Шаг 4: Автоматический вердикт ИИ по новым заявкам ---")
print(df_scoring_report)

# --- ШАГ №5: АВТОМАТИЧЕСКИЙ ЭКСПОРТ СКОРИНГ-ОТЧЕТА НА ДИСК ---

# Прописываем жесткий абсолютный путь к нашей целевой папке
target_path = r"E:\sh0tny1\рабочий стол\Yerlan\инфо по курсу Python без видео\файлы csv для Power BI\scoring_report.csv"

# Сохраняем отчет на диск (без технических индексов строк)
df_scoring_report.to_csv(target_path, index=False)

print("\n--- Шаг 5 выполнен успешно! ---")
print("Кредитный отчет ИИ отправлен в папку 'файлы csv для Power BI'!")
