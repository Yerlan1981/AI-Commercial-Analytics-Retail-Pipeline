import pandas as pd
import numpy as np

# 1. Фиксируем случайность для генерации данных
np.random.seed(42)

# 2. Имитируем историю покупок за последний месяц (10 транзакций)
# 'recency_days' - сколько дней назад была последняя покупка клиента
df_sales = pd.DataFrame({
    "client_id":[101, 102, 101, 103, 102, 104, 101, 105, 102, 103],
    "recency_days":[2, 15, 2, 28, 15, 5, 2, 30, 15, 28],
    "amount": [15000, 5000, 45000, 12000, 3500, 6000, 25000, 90000, 5000, 4000]
})

print("--- Шаг 1: Историческая база продаж для RFM создана ---")
print(df_sales)

# --- ШАГ №2: ГРУППИРОВКА И РАСЧЕТ ПОКАЗАТЕЛЕЙ R, F, M ---R (Recency — Давность): Как давно клиент покупал у нас в последний раз?
# F (Frequency — Частота): Как часто он покупает?  M (Monetary — Деньги): Сколько суммарно денег он принес в кассу?

# Группируем по клиентам и рассчитываем метрики для каждого
df_rfm = df_sales.groupby("client_id").agg({
    "recency_days": "min",   # Минимальное число дней = самая свежая покупка
    "client_id": "count",    # Сколько всего раз клиент покупал
    "amount": "sum"          # Общая сумма всех покупок клиента
})

# Переименовываем колонки, чтобы они соответствовали бизнес-логике RFM
df_rfm.columns = ["Recency", "Frequency", "Monetary"]

print("\n--- Шаг 2: Базовые показатели RFM по каждому клиенту ---")
print(df_rfm)

# --- ШАГ №3: АВТОМАТИЧЕСКОЕ ПРИСВОЕНИЕ БАЛЛОВ R, F, M ---

# 1. Оцениваем Давность (Recency): меньше дней -> выше балл (labels=[3, 2, 1])
df_rfm["R_Score"] = pd.qcut(df_rfm["Recency"], q=3, labels=[3, 2, 1])

# 2. Оцениваем Частоту (Frequency): больше покупок -> выше балл. 
# Используем duplicates="drop", чтобы сгладить одинаковые значения частоты
df_rfm["F_Score"] = pd.qcut(df_rfm["Frequency"], q=3, labels=[1, 2, 3], duplicates="drop")

# 3. Оцениваем Деньги (Monetary): больше сумма -> выше балл (labels=[1, 2, 3])
df_rfm["M_Score"] = pd.qcut(df_rfm["Monetary"], q=3, labels=[1, 2, 3])

print("\n--- Шаг 3: Таблица клиентов с выставленными баллами RFM ---")
print(df_rfm[["Recency", "R_Score", "Frequency", "F_Score", "Monetary", "M_Score"]])

# --- ШАГ №4: ИТОГОВАЯ БИЗНЕС-СЕГМЕНТАЦИЯ КЛИЕНТОВ ---

# 1. Считаем общую сумму баллов (переводим категории в обычные числа через .astype(int))
df_rfm["Total_Score"] = df_rfm["R_Score"].astype(int) + df_rfm["M_Score"].astype(int)

# 2. Пишем функцию, которая ставит понятный диагноз для коммерческого директора
def get_segment(score):
    if score >= 5:
        return "VIP-Клиент"
    elif score >= 3:
        return "Лояльный (Постоянный)"
    else:
        return "Уходящий / Зона риска"

# 3. Применяем функцию ко всей базе с помощью метода .apply()
df_rfm["Segment"] = df_rfm["Total_Score"].apply(get_segment)

print("\n--- Шаг 4: Финальный коммерческий отчет по сегментам клиентов ---")
print(df_rfm[["Total_Score", "Segment"]])

# --- ШАГ №5: АВТОМАТИЧЕСКИЙ ЭКСПОРТ RFM-ОТЧЕТА НА ДИСК ---

