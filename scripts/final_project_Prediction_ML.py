import pandas as pd
import numpy as np
from sklearn.linear_model import LinearRegression

# 1. Фиксируем случайность
np.random.seed(42)

# 2. Имитируем историю продаж компании за последние 6 месяцев (с января по июнь)
# month_num (X) - порядковый номер месяца (независимая переменная)
# sales_revenue (Y) - выручка в миллионах тенге (зависимая переменная)
df_history = pd.DataFrame({
    "month_num":[1, 2, 3, 4, 5, 6],
    "sales_revenue": [10.5, 12.2, 11.8, 14.1, 15.6, 16.3]
})

print("--- Шаг 1: Исторические данные для обучения модели созданы ---")
print(df_history)

# --- ШАГ №2: ПОДГОТОВКА ДАННЫХ ---
X = df_history[["month_num"]] # Фактор (двумерная матрица)
y = df_history["sales_revenue"] # Цель (выручка)

# --- ШАГ №3: ИНИЦИАЛИЗАЦИЯ И ОБУЧЕНИЕ МОДЕЛИ ИИ ---

# 1. Создаем пустой "мозг" модели Линейной Регрессии
model = LinearRegression()

# 2. Запускаем обучение! Модель сканирует X и y, выстраивая идеальную линию тренда
model.fit(X, y)

print("\n--- Шаг 3: Модель ИИ успешно обучена на исторических данных! ---")
print("Коэффициент направления тренда (k):", np.round(model.coef_, 2))

# --- ШАГ №4: ГЕНЕРАЦИЯ БУДУЩЕГО И МАТЕМАТИЧЕСКИЙ ПРОГНОЗ ВЫРУЧКИ ---

# 1. Создаем матрицу будущих месяцев (7, 8, 9) в двумерном формате
X_future = pd.DataFrame({"month_num": [7, 8, 9]})

# 2. Модель ИИ берет линию тренда и рассчитывает по ней прогноз выручки
future_predictions = model.predict(X_future)

# 3. Объединяем будущие месяцы и прогнозы в один красивый прогнозный датафрейм
df_forecast = pd.DataFrame({
    "month_num":[7, 8, 9],
    "predicted_revenue": np.round(future_predictions, 2)
})

print("\n--- Шаг 4: Точный математический прогноз ИИ на 3 месяца вперед ---")
print(df_forecast)

# --- ШАГ №5: АВТОМАТИЧЕСКИЙ ЭКСПОРТ ПРОГНОЗА НА ДИСК ---

# Прописываем жесткий путь к нашей папке (используем r перед кавычками)
target_path = r"E:\sh0tny1\рабочий стол\Yerlan\инфо по курсу Python без видео\файлы csv для Power BI\sales_forecast.csv"

# Сохраняем прогнозную таблицу на диск (index=False, чтобы не плодить мусорные индексы)
df_forecast.to_csv(target_path, index=False)

print("\n--- Шаг 5 выполнен успешно! ---")
print("Математический прогноз ИИ отправлен в папку 'файлы csv для Power BI'!")
