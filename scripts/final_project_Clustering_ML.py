import pandas as pd
import numpy as np
# Импортируем алгоритм К-средних (K-Means) для задачи кластеризации (обучение без учителя)
from sklearn.cluster import KMeans
# Модуль cluster из библиотеки sklearn один из математических инструментов для группировки данных и поиска скрытых паттернов

# 1. Фиксируем случайность
np.random.seed(42)

# 2. Имитируем базу клиентов для поиска скрытых групп
# age - возраст клиента
# avg_check_kZT - средний чек в тысячах тенге
df_shop_customers = pd.DataFrame({
    "age":[22, 25, 45, 48, 23, 50],
    "avg_check_kZT": [15, 18, 55, 60, 12, 65]
})

print("--- Шаг 1: База клиентов для поиска скрытых кластеров создана ---")
print(df_shop_customers)

# --- ШАГ №2: ВЫДЕЛЕНИЕ МАТРИЦЫ ПРИЗНАКОВ ДЛЯ КЛАСТЕРИЗАЦИИ (X) ---

# Передаем оба столбца-характеристики в двойных квадратных скобках
X = df_shop_customers[["age", "avg_check_kZT"]]

print("\n--- Шаг 2: Матрица признаков X успешно подготовлена ---")
print("Формат матрицы факторов X (строки, колонки):", X.shape)

# --- ШАГ №3: ИНИЦИАЛИЗАЦИЯ И ОБУЧЕНИЕ МОДЕЛИ КЛАСТЕРИЗАЦИИ ИИ ---

# 1. Создаем пустой "мозг" модели KMeans и жестко приказываем разделить базу на 2 группы
# random_state=42 нужен, чтобы группы всегда получались одинаковыми при каждом запуске
model_kmeans = KMeans(n_clusters=2, random_state=42)

# 2. Запускаем обучение! Модель сканирует матрицу X и ищет центры двух скрытых кучек
model_kmeans.fit(X)

print("\n--- Шаг 3: Модель KMeans успешно обучена! Скрытые группы найдены! ---")

# --- ШАГ №4: ИЗВЛЕЧЕНИЕ МЕТОК КЛАСТЕРОВ И ФОРМИРОВАННЫЙ ОТЧЕТ ---

# 1. Забираем из обученной модели массив с номерами присвоенных групп
labels = model_kmeans.labels_

# 2. Добавляем номера кластеров в виде нового столбца в нашу исходную таблицу
df_shop_customers["Cluster_ID"] = labels

print("\n--- Шаг 4: Итоговая таблица клиентов с номерами скрытых групп ---")
print(df_shop_customers)

# --- ШАГ №5: АВТОМАТИЧЕСКИЙ ЭКСПОРТ РЕЗУЛЬТАТОВ КЛАСТЕРИЗАЦИИ НА ДИСК ---

# Прописываем жесткий абсолютный путь к нашей целевой папке
target_path = r"E:\sh0tny1\рабочий стол\Yerlan\инфо по курсу Python без видео\файлы csv для Power BI\clusters_report.csv"

# Сохраняем отчет на диск (index=False, чтобы не плодить технические индексы)
df_shop_customers.to_csv(target_path, index=False)

print("\n--- Шаг 5 выполнен успешно! ---")
print("Отчет по кластеризации ИИ отправлен в папку 'файлы csv для Power BI'!")
